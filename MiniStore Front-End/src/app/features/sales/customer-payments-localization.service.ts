@Injectable({ providedIn: 'root' })
export class CustomerPaymentsLocalizationService {
  private readonly session = inject(ApiSessionService);
  text(key: CustomerPaymentKey) {
    return m[this.session.session()?.culture?.startsWith('ar') ? 'ar' : 'en'][key];
  }
  status(value: number) {
    return this.text((['', 'draft', 'posted', 'reversed'][value] ?? 'draft') as CustomerPaymentKey);
  }
}
