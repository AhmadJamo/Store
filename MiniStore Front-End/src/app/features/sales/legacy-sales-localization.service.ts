export type LegacySalesKey = keyof typeof copy.en;
@Injectable({ providedIn: 'root' })
export class LegacySalesLocalizationService {
  private readonly session = inject(ApiSessionService);
  text(key: LegacySalesKey) {
    return copy[this.session.session()?.culture?.startsWith('ar') ? 'ar' : 'en'][key];
  }
  channel(value: number) {
    return this.text(value === 2 ? 'pos' : 'wholesale');
  }
  discount(value: number) {
    return this.text(value === 2 ? 'fixed' : 'percentage');
  }
}
