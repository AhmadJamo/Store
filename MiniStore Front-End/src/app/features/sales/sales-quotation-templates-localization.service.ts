export type TemplateKey = keyof typeof m.en;
@Injectable({ providedIn: 'root' })
export class SalesQuotationTemplatesLocalizationService {
  private readonly s = inject(ApiSessionService);
  text(k: TemplateKey) {
    return m[this.s.session()?.culture?.startsWith('ar') ? 'ar' : 'en'][k];
  }
  status(v: number) {
    return this.text((['', 'draft', 'active', 'archived'][v] ?? 'draft') as TemplateKey);
  }
  type(v: number) {
    return this.text((['', 'required', 'optional', 'alternative'][v] ?? 'required') as TemplateKey);
  }
}
